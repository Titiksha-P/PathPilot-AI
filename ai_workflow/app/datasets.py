def all_pathway_ids() -> set[str]:
    return {
        *(item["id"] for item in STREAM_PATHWAYS),
        *(item["id"] for item in COURSE_PATHWAYS),
        *(item["id"] for item in CAREERS),
    }


def get_course(course_id: str) -> dict:
    for course in COURSE_PATHWAYS:
        if course["id"] == course_id:
            return course
    raise ValueError(f"Unknown course pathway: {course_id}")
